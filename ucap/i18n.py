def t(lang: str, key: str, **kw) -> str:
    s = STRINGS.get(lang, STRINGS["id"]).get(key) or STRINGS["id"].get(key, key)
    return s.format(**kw) if kw else s


def error_text(lang: str, err) -> str:
    code = getattr(err, "code", "unknown")
    detail = (getattr(err, "detail", "") or str(err))[:160]
    return t(lang, f"err_{code}", detail=detail) if f"err_{code}" in STRINGS["id"] else t(lang, "err_unknown", detail=detail)
